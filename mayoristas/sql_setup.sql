    CREATE INDEX IX_MAYORISTAS_VENDEDOR
        ON BI_REPORTE_VENTAS_MAYORISTA (VENDEDOR)
        INCLUDE (FECHA, CANT_FACTURADA, CLIENTE, RUBRO, CATEGORIA);
