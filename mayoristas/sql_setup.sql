    CREATE INDEX IX_MAYORISTAS_CLIENTE
        ON BI_REPORTE_VENTAS_MAYORISTA (CLIENTE)
        INCLUDE (FECHA, CANT_FACTURADA, VENDEDOR, RUBRO, CATEGORIA);
